// Emulated global interrupt mask
static uint16_t __OSGlobalIntMask = 0;

// Simulated MI register (memory-mapped I/O)
static uint16_t MI_INTR_MASK_REG_EMU = 0;

extern "C" uint32_t osSetIntMask(uint32_t mask)
{
    // Previous "CP0 Status" placeholder
    uint32_t status = 0;

    uint16_t oldMask = __OSGlobalIntMask;
    uint16_t newMask = mask & MI_INTR_MASK;

    // Lookup table index
    uint16_t lutIndex = newMask & 0x3F;
    uint16_t lutVal = osRcpImTable[lutIndex];

    MI_INTR_MASK_REG_EMU = lutVal;
    __OSGlobalIntMask = mask;

    return status;
}

// Optional accessor for testing or debug
extern "C" uint16_t getEmuMaskReg()
{
    return MI_INTR_MASK_REG_EMU;
}