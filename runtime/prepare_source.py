#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.60 — Guarded Injection & Path Sanitization
═══════════════════════════════════════════════════════════════════════════════
LOG 71 — Resolving 'G_TRI2' redefinition and header collisions.
═══════════════════════════════════════════════════════════════════════════════
"""

class SourceHarmonizerV7560:
    def __init__(self):
        self.workspace = Path(os.getenv('GITHUB_WORKSPACE', os.getcwd())).resolve()
        self.src_root = self.workspace / "decomp-files" / "src"
        self.function_map = {}
        # Define only if missing from the port's internal headers
        self.required_defines = {
            "G_TRI2": "0x11"
        }

    def index_functions(self):
        print("[>] Indexing engine functions for JNI visibility...")
        # Pattern for standard N64-style function definitions
        def_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        for root, _, files in os.walk(str(self.src_root)):
            for file in files:
                if file.endswith('.c'):
                    file_path = Path(root) / file
                    try:
                        content = file_path.read_text(encoding='utf-8', errors='ignore')
                        for match in def_pat.finditer(content):
                            ret_type, name, params = match.groups()
                            # Strip 'static' to allow the JNI bridge to link globally
                            ret_type = " ".join(ret_type.split()).replace("static ", "")
                            self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
                    except Exception:
                        continue

    def write_sh_signatures(self):
        include_dir = self.workspace / "decomp-files" / "include"
        include_dir.mkdir(parents=True, exist_ok=True)
        header_path = include_dir / "sh_signatures.h"
        
        lines = [
            "#ifndef SH_SIGNATURES_H",
            "#define SH_SIGNATURES_H",
            "",
            "// Automatically generated by SourceHarmonizer v75.60",
            "// Log 71: Using guarded defines to prevent redefinition errors",
            ""
        ]
        
        # Guarded Injection: Only define if not already present in GBI headers
        for define, value in self.required_defines.items():
            lines.append(f"#ifndef {define}")
            lines.append(f"    #define {define} {value}")
            lines.append("#endif\n")
        
        lines.append("// Global Symbol Visibility")
        for name in sorted(self.function_map.keys()):
            lines.append(self.function_map[name])
            
        lines.append("\n#endif // SH_SIGNATURES_H")
        
        header_path.write_text("\n".join(lines), encoding='utf-8')
        print(f"[+] Guarded header written to: {header_path}")

    def run(self):
        self.index_functions()
        self.write_sh_signatures()

if __name__ == "__main__":
    SourceHarmonizerV7560().run()
