#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.31 — Global Truth Injection

═══════════════════════════════════════════════════════════════════════════════
LOG 55 — v75.30 mapped 3823 signatures but failed to 'reify' (0 fixed).
Reason: Depended on local comment tags that don't exist in all files.
═══════════════════════════════════════════════════════════════════════════════

KEY UPGRADES in v75.31:
  1. Centralized Truth: Generates 'include/sh_signatures.h' with ALL mapped 
     signatures as 'extern' declarations.
  2. Foundation Integration: Automatically appends the signature header to 
     sh_foundation.h, ensuring global visibility.
  3. Redundant Cleanup: Removes any old, local "SH Auto-Prototype" blocks to 
     prevent "duplicate declaration" errors.
"""

class SourceHarmonizerV7531:
    def __init__(self):
        self.root = Path(os.getcwd())
        self.target_dir = self.find_project_root()
        self.function_map = {} 
        self.stats = {"signatures_mapped": 0, "files_cleaned": 0}

    def find_project_root(self):
        for p in [self.root, self.root / "Android/app/src/main/cpp"]:
            if (p / "src").exists(): return p
        return self.root

    def map_all_functions(self):
        print("[>] Indexing project signatures...")
        # Catch: [Return] [Name]([Params]) {
        def_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        for file_path in self.target_dir.rglob('*.c'):
            content = file_path.read_text(encoding='utf-8', errors='ignore')
            for match in def_pat.finditer(content):
                ret_type, name, params = match.groups()
                ret_type = " ".join(ret_type.split())
                # Store the most complete version of the signature
                self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
        
        self.stats["signatures_mapped"] = len(self.function_map)

    def generate_truth_header(self):
        print(f"[>] Generating sh_signatures.h with {self.stats['signatures_mapped']} entries...")
        header_path = self.target_dir / "include" / "sh_signatures.h"
        
        content = "#ifndef SH_SIGNATURES_H\n#define SH_SIGNATURES_H\n\n"
        content += "// Automatically generated by SH v75.31\n\n"
        for sig in sorted(self.function_map.values()):
            content += sig + "\n"
        content += "\n#endif\n"
        
        header_path.write_text(content)

        # Ensure sh_foundation.h includes this
        foundation_path = self.target_dir / "include" / "sh_foundation.h"
        if foundation_path.exists():
            f_content = foundation_path.read_text()
            if 'sh_signatures.h' not in f_content:
                # Add it before the final #endif
                f_content = f_content.replace("#endif", '#include "sh_signatures.h"\n#endif')
                foundation_path.write_text(f_content)

    def cleanup_local_blocks(self):
        """Removes the messy local prototype blocks from previous versions."""
        print("[>] Cleaning up redundant local prototypes...")
        proto_block_pat = re.compile(r'// --- SH (?:Auto|Precise)-Prototypes ---.*?// -+', re.DOTALL)
        
        for file_path in self.target_dir.rglob('*.c'):
            content = file_path.read_text(encoding='utf-8', errors='ignore')
            if "SH" in content and "Prototypes" in content:
                new_content = proto_block_pat.sub("", content)
                if new_content != content:
                    file_path.write_text(new_content)
                    self.stats["files_cleaned"] += 1

    def run(self):
        self.map_all_functions()
        if self.stats["signatures_mapped"] > 0:
            self.generate_truth_header()
            self.cleanup_local_blocks()
        
        print(f"\n[+] v75.31 Global Truth Injection Complete.")
        print(f"    - Global Signatures Harmonized: {self.stats['signatures_mapped']}")
        print(f"    - Local Cleanup Performed: {self.stats['files_cleaned']} files")

if __name__ == "__main__":
    SourceHarmonizerV7531().run()
