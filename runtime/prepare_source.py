#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.55 — Macro Resolution & Global Injection
═══════════════════════════════════════════════════════════════════════════════
LOG 70 — Addressing undeclared 'G_TRI2' and macro expansion failures.
═══════════════════════════════════════════════════════════════════════════════
"""

class SourceHarmonizerV7555:
    def __init__(self):
        self.workspace = Path(os.getenv('GITHUB_WORKSPACE', os.getcwd())).resolve()
        self.src_root = self.workspace / "decomp-files" / "src"
        self.function_map = {}
        # Known missing identifiers for AArch64/OTR ports
        self.missing_defines = {
            "G_TRI2": "0x11" 
        }

    def index_functions(self):
        print("[>] Scanning for C signatures and ensuring global visibility...")
        def_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        found_count = 0
        for root, _, files in os.walk(str(self.src_root)):
            for file in files:
                if file.endswith('.c'):
                    file_path = Path(root) / file
                    try:
                        content = file_path.read_text(encoding='utf-8', errors='ignore')
                        for match in def_pat.finditer(content):
                            ret_type, name, params = match.groups()
                            ret_type = " ".join(ret_type.split()).replace("static ", "")
                            self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
                            found_count += 1
                    except Exception:
                        continue
        
        print(f"[+] Indexed {len(self.function_map)} functions.")

    def write_sh_signatures(self):
        include_dir = self.workspace / "decomp-files" / "include"
        include_dir.mkdir(parents=True, exist_ok=True)
        header_path = include_dir / "sh_signatures.h"
        
        lines = [
            "#ifndef SH_SIGNATURES_H",
            "#define SH_SIGNATURES_H",
            "",
            "// Automatically generated by SourceHarmonizer v75.55",
            "// FIX: Injecting missing GBI/Microcode constants",
        ]
        
        # Inject missing defines identified in Log 70
        for define, value in self.missing_defines.items():
            lines.append(f"#ifndef {define}\n  #define {define} {value}\n#endif")
        
        lines.append("\n// Global Function Signatures")
        for name in sorted(self.function_map.keys()):
            lines.append(self.function_map[name])
            
        lines.append("\n#endif // SH_SIGNATURES_H")
        
        header_path.write_text("\n".join(lines), encoding='utf-8')
        print(f"[+] Master Header updated with Log 70 fixes at: {header_path}")

    def run(self):
        self.index_functions()
        self.write_sh_signatures()

if __name__ == "__main__":
    SourceHarmonizerV7555().run()
