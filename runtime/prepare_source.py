#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.80 — Shadow Removal & Static Stripping
═══════════════════════════════════════════════════════════════════════════════
LOG 73 — Resolved 'conflicting types' by stripping 'static' from source files.
═══════════════════════════════════════════════════════════════════════════════
"""

class SourceHarmonizerV7580:
    def __init__(self):
        self.workspace = Path(os.getenv('GITHUB_WORKSPACE', os.getcwd())).resolve()
        self.src_root = self.workspace / "decomp-files" / "src"
        self.function_map = {}

    def process_sources(self):
        print("[>] Scanning engine and stripping static qualifiers...")
        # Matches: static [Type] [Name]([Params]) {
        static_pat = re.compile(r'^static\s+([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        # Matches: [Type] [Name]([Params]) {
        global_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        for root, _, files in os.walk(str(self.src_root)):
            for file in files:
                if file.endswith('.c'):
                    file_path = Path(root) / file
                    try:
                        content = file_path.read_text(encoding='utf-8', errors='ignore')
                        original_content = content
                        
                        # 1. Strip 'static' from definitions to avoid scope conflicts
                        content = static_pat.sub(r'\1 \2(\3) {', content)
                        
                        if content != original_content:
                            file_path.write_text(content, encoding='utf-8')
                        
                        # 2. Index for the global header
                        for match in global_pat.finditer(content):
                            ret_type, name, params = match.groups()
                            ret_type = " ".join(ret_type.split())
                            self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
                            
                    except Exception as e:
                        print(f"[!] Skip {file}: {e}")

    def write_header(self):
        include_dir = self.workspace / "decomp-files" / "include"
        include_dir.mkdir(parents=True, exist_ok=True)
        header_path = include_dir / "sh_signatures.h"
        
        lines = [
            "#ifndef SH_SIGNATURES_H",
            "#define SH_SIGNATURES_H",
            "#include <PR/gbi.h>",
            "",
            "// Generated by SH v75.80",
            "// All functions stripped of 'static' in source for JNI visibility",
            ""
        ]
        
        for name in sorted(self.function_map.keys()):
            lines.append(self.function_map[name])
            
        lines.append("\n#endif")
        header_path.write_text("\n".join(lines), encoding='utf-8')
        print(f"[+] Harmonization complete. {len(self.function_map)} functions exported.")

    def run(self):
        self.process_sources()
        self.write_header()

if __name__ == "__main__":
    SourceHarmonizerV7580().run()