#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.32 — Recursive Directory Insurance

═══════════════════════════════════════════════════════════════════════════════
LOG 56 — FileNotFoundError when writing sh_signatures.h.
Reason: include/ directory was not created before writing.
═══════════════════════════════════════════════════════════════════════════════

KEY UPGRADES in v75.32:
  1. Directory Insurance: Uses mkdir(parents=True) to ensure the include path
     exists before generating the global truth header.
  2. Signature Sanitization: Strips 'static' and 'inline' keywords from the 
     global header to ensure symbols remain visible to the linker.
  3. Forced Encoding: Explicitly uses utf-8 for all file operations to prevent
     runner-specific locale crashes.
"""

class SourceHarmonizerV7532:
    def __init__(self):
        self.root = Path(os.getcwd())
        self.target_dir = self.find_project_root()
        self.function_map = {} 
        self.stats = {"signatures_mapped": 0, "files_cleaned": 0}

    def find_project_root(self):
        # Scan for the actual source container
        for p in [self.root, self.root / "Android/app/src/main/cpp"]:
            if (p / "src").exists(): return p
        return self.root

    def map_all_functions(self):
        print("[>] Indexing project signatures...")
        # Catch: [Return] [Name]([Params]) {
        def_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        for file_path in self.target_dir.rglob('*.c'):
            try:
                content = file_path.read_text(encoding='utf-8', errors='ignore')
                for match in def_pat.finditer(content):
                    ret_type, name, params = match.groups()
                    # Clean return type: remove static/inline which shouldn't be in externs
                    ret_type = " ".join(ret_type.split())
                    ret_type = ret_type.replace("static ", "").replace("inline ", "")
                    self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
            except Exception:
                continue
        
        self.stats["signatures_mapped"] = len(self.function_map)

    def generate_truth_header(self):
        print(f"[>] Generating sh_signatures.h with {self.stats['signatures_mapped']} entries...")
        
        # FIX: Ensure the directory exists before writing
        include_dir = self.target_dir / "include"
        include_dir.mkdir(parents=True, exist_ok=True)
        
        header_path = include_dir / "sh_signatures.h"
        
        content = "#ifndef SH_SIGNATURES_H\n#define SH_SIGNATURES_H\n\n"
        content += "// Automatically generated by SH v75.32\n\n"
        # Filter out duplicates and sort
        unique_sigs = sorted(list(set(self.function_map.values())))
        for sig in unique_sigs:
            content += sig + "\n"
        content += "\n#endif\n"
        
        header_path.write_text(content, encoding='utf-8')

        # Link to foundation if it exists
        foundation_path = include_dir / "sh_foundation.h"
        if foundation_path.exists():
            f_content = foundation_path.read_text(encoding='utf-8', errors='ignore')
            if 'sh_signatures.h' not in f_content:
                f_content = f_content.replace("#endif", '#include "sh_signatures.h"\n#endif')
                foundation_path.write_text(f_content, encoding='utf-8')

    def cleanup_local_blocks(self):
        print("[>] Cleaning up redundant local prototypes...")
        proto_block_pat = re.compile(r'// --- SH (?:Auto|Precise)-Prototypes ---.*?// -+', re.DOTALL)
        
        for file_path in self.target_dir.rglob('*.c'):
            try:
                content = file_path.read_text(encoding='utf-8', errors='ignore')
                if "SH" in content and "Prototypes" in content:
                    new_content = proto_block_pat.sub("", content)
                    if new_content != content:
                        file_path.write_text(new_content, encoding='utf-8')
                        self.stats["files_cleaned"] += 1
            except Exception:
                continue

    def run(self):
        self.map_all_functions()
        if self.stats["signatures_mapped"] > 0:
            self.generate_truth_header()
            self.cleanup_local_blocks()
        
        print(f"\n[+] v75.32 Robust Architect Complete.")
        print(f"    - Global Signatures Harmonized: {self.stats['signatures_mapped']}")
        print(f"    - Environment Verified: {self.target_dir}")

if __name__ == "__main__":
    SourceHarmonizerV7532().run()
