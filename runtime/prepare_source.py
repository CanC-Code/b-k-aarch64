#!/usr/bin/env python3
import os
import re
from pathlib import Path

"""
SourceHarmonizer v75.35 — Absolute Path Stability
═══════════════════════════════════════════════════════════════════════════════
LOG 66 — Replaced all rglob/pathlib iterations with os.walk for CI stability.
═══════════════════════════════════════════════════════════════════════════════
"""

class SourceHarmonizerV7535:
    def __init__(self):
        # Use absolute path resolution for the runner environment
        self.root = Path(os.getcwd()).resolve()
        self.src_path = os.path.join(str(self.root), "decomp-files", "src")
        self.function_map = {} 

    def verify_environment(self):
        print(f"[>] Root Directory: {self.root}")
        print(f"[>] Target Source: {self.src_path}")
        
        if not os.path.exists(self.src_path):
            print(f"[!] Error: Source path not found at {self.src_path}")
            # Diagnostic: check if the submodule actually checked out
            base_decomp = os.path.join(str(self.root), "decomp-files")
            if os.path.exists(base_decomp):
                print(f"[i] decomp-files exists. Contents: {os.listdir(base_decomp)}")
            os._exit(1)

    def index_functions(self):
        print("[>] Scanning C files for function signatures...")
        # Regex to capture standard engine function patterns
        def_pat = re.compile(r'^([\w\s\*]+?)\b(func_[A-Z0-9_]+)\s*\(([^)]*)\)\s*\{', re.MULTILINE)
        
        for root, _, files in os.walk(self.src_path):
            for file in files:
                if file.endswith('.c'):
                    full_path = os.path.join(root, file)
                    try:
                        with open(full_path, 'r', encoding='utf-8', errors='ignore') as f:
                            content = f.read()
                            for match in def_pat.finditer(content):
                                ret_type, name, params = match.groups()
                                # Clean up return types (remove storage specifiers)
                                ret_type = " ".join(ret_type.split()).replace("static ", "").replace("inline ", "")
                                self.function_map[name] = f"extern {ret_type} {name}({params.strip()});"
                    except Exception as e:
                        print(f"[!] Failed to process {file}: {e}")

    def write_header(self):
        out_dir = os.path.join(str(self.root), "decomp-files", "include")
        os.makedirs(out_dir, exist_ok=True)
        header_file = os.path.join(out_dir, "sh_signatures.h")
        
        output = "#ifndef SH_SIGNATURES_H\n#define SH_SIGNATURES_H\n\n"
        output += "// Auto-generated by SourceHarmonizer v75.35\n\n"
        
        # Sort and deduplicate signatures
        for sig in sorted(list(set(self.function_map.values()))):
            output += sig + "\n"
        
        output += "\n#endif\n"
        
        with open(header_file, 'w', encoding='utf-8') as f:
            f.write(output)

    def execute(self):
        self.verify_environment()
        self.index_functions()
        if self.function_map:
            self.write_header()
            print(f"\n[+] Harmonization success. {len(self.function_map)} unique functions indexed.")
        else:
            print("[!] Critical: No functions found. Check submodule depth.")

if __name__ == "__main__":
    SourceHarmonizerV7535().execute()
